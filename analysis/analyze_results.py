import os
import sys
import csv

# Set safe writable Matplotlib cache directory before importing matplotlib
os.environ.setdefault("MPLCONFIGDIR", "/tmp/matplotlib_cache")

REQUIRED_COLUMNS = [
    "scenario",
    "cache",
    "accesses",
    "hits",
    "misses",
    "hit_rate",
    "miss_rate",
    "mem_word_reads",
    "total_cycles",
    "average_cycles",
]

CSV_PATH = os.path.join("results", "results.csv")
OUT_DIR  = "results"

SCENARIO_DISPLAY_NAMES = {
    "scenario_1_sequential_locality": "Scenario 1:\nSequential",
    "scenario_2_conflict_heavy":      "Scenario 2:\nConflict-Heavy",
    "scenario_3_explicit_lru":        "Scenario 3:\nExplicit LRU",
    "scenario_4_mixed_trace":         "Scenario 4:\nMixed Trace",
}

CACHE_DISPLAY_NAMES = {
    "direct_mapped": "Direct-Mapped",
    "two_way":       "2-Way LRU",
}


def validate_and_load_csv(csv_path):
    """
    Parses and thoroughly validates the CSV generated by the testbench.
    Ensures correct types, absence of zero-access errors, invariant consistency,
    and presence of both caches for each scenario.
    """
    if not os.path.isfile(csv_path):
        print(f"[ERROR] Results file '{csv_path}' not found! Run the simulation first.", file=sys.stderr)
        sys.exit(1)

    records = []
    with open(csv_path, mode="r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)

        # 1. Verify required column headers exist
        missing_cols = [c for c in REQUIRED_COLUMNS if c not in reader.fieldnames]
        if missing_cols:
            print(f"[ERROR] Missing required CSV columns: {missing_cols}", file=sys.stderr)
            sys.exit(1)

        for row_idx, row in enumerate(reader, start=2):
            scenario = row["scenario"].strip()
            cache    = row["cache"].strip()

            # 2. Validate numeric values
            try:
                accesses       = int(row["accesses"])
                hits           = int(row["hits"])
                misses         = int(row["misses"])
                mem_word_reads = int(row["mem_word_reads"])
                total_cycles   = int(row["total_cycles"])
            except ValueError as e:
                print(f"[ERROR] Non-integer value in row {row_idx}: {e}", file=sys.stderr)
                sys.exit(1)

            # 3. Check for zero-access division error
            if accesses <= 0:
                print(f"[ERROR] Zero or negative accesses ({accesses}) in row {row_idx}", file=sys.stderr)
                sys.exit(1)

            # 4. Verify invariant: hits + misses == accesses
            if hits + misses != accesses:
                print(
                    f"[ERROR] Invariant violated in row {row_idx}: hits({hits}) + misses({misses}) != accesses({accesses})",
                    file=sys.stderr,
                )
                sys.exit(1)

            # 5. Verify invariant: mem_word_reads == 4 * misses
            if mem_word_reads != 4 * misses:
                print(
                    f"[ERROR] Invariant violated in row {row_idx}: mem_word_reads({mem_word_reads}) != 4 * misses({misses})",
                    file=sys.stderr,
                )
                sys.exit(1)

            # 6. Recalculate metrics directly from raw counters
            hit_rate        = (hits / accesses) * 100.0
            miss_rate       = (misses / accesses) * 100.0
            average_latency = total_cycles / accesses

            records.append({
                "scenario":        scenario,
                "cache":           cache,
                "accesses":        accesses,
                "hits":            hits,
                "misses":          misses,
                "mem_word_reads":  mem_word_reads,
                "total_cycles":    total_cycles,
                "hit_rate":        hit_rate,
                "miss_rate":       miss_rate,
                "average_latency": average_latency,
            })

    if not records:
        print(f"[ERROR] Results file '{csv_path}' is empty!", file=sys.stderr)
        sys.exit(1)

    # 7. Check that each scenario has both cache implementations
    scenarios_seen = {}
    for r in records:
        scenarios_seen.setdefault(r["scenario"], set()).add(r["cache"])

    for sc, caches in scenarios_seen.items():
        if "direct_mapped" not in caches or "two_way" not in caches:
            print(f"[ERROR] Scenario '{sc}' does not contain both 'direct_mapped' and 'two_way'!", file=sys.stderr)
            sys.exit(1)

    return records


def print_summary_table(records):
    """Prints a structured, publication-grade ASCII summary table."""
    print("\n" + "=" * 115)
    print("                    2-WAY SET-ASSOCIATIVE VS DIRECT-MAPPED CACHE PERFORMANCE SUMMARY")
    print("=" * 115)
    header = (
        f"{'Scenario':<32} {'Cache Type':<15} {'Accesses':>9} {'Hits':>6} {'Misses':>7} "
        f"{'Hit Rate':>10} {'Mem Reads':>10} {'Total Cyc':>10} {'Avg Latency':>12}"
    )
    print(header)
    print("-" * 115)

    last_sc = None
    for r in records:
        if last_sc is not None and last_sc != r["scenario"]:
            print("-" * 115)
        last_sc = r["scenario"]

        cache_label = CACHE_DISPLAY_NAMES.get(r["cache"], r["cache"])
        print(
            f"{r['scenario']:<32} "
            f"{cache_label:<15} "
            f"{r['accesses']:>9d} "
            f"{r['hits']:>6d} "
            f"{r['misses']:>7d} "
            f"{r['hit_rate']:>9.2f}% "
            f"{r['mem_word_reads']:>10d} "
            f"{r['total_cycles']:>10d} "
            f"{r['average_latency']:>11.2f} c"
        )
    print("=" * 115 + "\n")


def generate_plots(records):
    """Generates three comparative grouped bar charts."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import numpy as np
    except ImportError:
        print("[WARNING] matplotlib is not installed. To generate plots, run:", file=sys.stderr)
        print("    pip install matplotlib", file=sys.stderr)
        return []

    # Organize data by scenario in stable insertion order
    scenarios = []
    dm_data = {}
    sa_data = {}

    for r in records:
        sc = r["scenario"]
        if sc not in scenarios:
            scenarios.append(sc)
        if r["cache"] == "direct_mapped":
            dm_data[sc] = r
        elif r["cache"] == "two_way":
            sa_data[sc] = r

    x_indices = np.arange(len(scenarios))
    bar_width = 0.35
    display_labels = [SCENARIO_DISPLAY_NAMES.get(s, s) for s in scenarios]

    os.makedirs(OUT_DIR, exist_ok=True)
    generated_plots = []

    # Palette
    color_dm = "#1f77b4" # Steel Blue
    color_sa = "#2ca02c" # Forest Green

    # -------------------------------------------------------------------------
    # Graph 1: Hit Rate Comparison (%)
    # -------------------------------------------------------------------------
    fig, ax = plt.subplots(figsize=(9, 5.5), dpi=300)
    dm_vals = [dm_data[s]["hit_rate"] for s in scenarios]
    sa_vals = [sa_data[s]["hit_rate"] for s in scenarios]

    rects1 = ax.bar(x_indices - bar_width/2, dm_vals, bar_width, label="Direct-Mapped", color=color_dm, edgecolor="black")
    rects2 = ax.bar(x_indices + bar_width/2, sa_vals, bar_width, label="2-Way Set-Associative (LRU)", color=color_sa, edgecolor="black")

    ax.set_ylabel("Hit Rate (%)", fontsize=12, fontweight="bold")
    ax.set_title("Cache Hit Rate Comparison: Direct-Mapped vs Two-Way LRU", fontsize=13, fontweight="bold", pad=12)
    ax.set_xticks(x_indices)
    ax.set_xticklabels(display_labels, fontsize=10)
    ax.set_ylim(0, 105)
    ax.grid(axis="y", linestyle="--", alpha=0.5)
    ax.legend(loc="upper right", framealpha=0.9)

    ax.bar_label(rects1, fmt="%.1f%%", padding=3, fontsize=9)
    ax.bar_label(rects2, fmt="%.1f%%", padding=3, fontsize=9)

    path1 = os.path.join(OUT_DIR, "hit_rate_comparison.png")
    fig.tight_layout()
    fig.savefig(path1)
    plt.close(fig)
    generated_plots.append(path1)
    print(f"[PLOT] Saved: {path1}")

    # -------------------------------------------------------------------------
    # Graph 2: Average Access Latency Comparison (Cycles/Access)
    # -------------------------------------------------------------------------
    fig, ax = plt.subplots(figsize=(9, 5.5), dpi=300)
    dm_lat = [dm_data[s]["average_latency"] for s in scenarios]
    sa_lat = [sa_data[s]["average_latency"] for s in scenarios]

    rects1 = ax.bar(x_indices - bar_width/2, dm_lat, bar_width, label="Direct-Mapped", color=color_dm, edgecolor="black")
    rects2 = ax.bar(x_indices + bar_width/2, sa_lat, bar_width, label="2-Way Set-Associative (LRU)", color=color_sa, edgecolor="black")

    ax.set_ylabel("Average Latency (Cycles / Access)", fontsize=12, fontweight="bold")
    ax.set_title("Average CPU Access Latency: Direct-Mapped vs Two-Way LRU", fontsize=13, fontweight="bold", pad=12)
    ax.set_xticks(x_indices)
    ax.set_xticklabels(display_labels, fontsize=10)
    ax.set_ylim(0, max(max(dm_lat), max(sa_lat)) * 1.25)
    ax.grid(axis="y", linestyle="--", alpha=0.5)
    ax.legend(loc="upper right", framealpha=0.9)

    ax.bar_label(rects1, fmt="%.2f", padding=3, fontsize=9)
    ax.bar_label(rects2, fmt="%.2f", padding=3, fontsize=9)

    path2 = os.path.join(OUT_DIR, "average_latency_comparison.png")
    fig.tight_layout()
    fig.savefig(path2)
    plt.close(fig)
    generated_plots.append(path2)
    print(f"[PLOT] Saved: {path2}")

    # -------------------------------------------------------------------------
    # Graph 3: Main Memory Word Reads Comparison
    # -------------------------------------------------------------------------
    fig, ax = plt.subplots(figsize=(9, 5.5), dpi=300)
    dm_reads = [dm_data[s]["mem_word_reads"] for s in scenarios]
    sa_reads = [sa_data[s]["mem_word_reads"] for s in scenarios]

    rects1 = ax.bar(x_indices - bar_width/2, dm_reads, bar_width, label="Direct-Mapped", color=color_dm, edgecolor="black")
    rects2 = ax.bar(x_indices + bar_width/2, sa_reads, bar_width, label="2-Way Set-Associative (LRU)", color=color_sa, edgecolor="black")

    ax.set_ylabel("Main Memory Word Reads (Words)", fontsize=12, fontweight="bold")
    ax.set_title("Memory Traffic Comparison: Direct-Mapped vs Two-Way LRU", fontsize=13, fontweight="bold", pad=12)
    ax.set_xticks(x_indices)
    ax.set_xticklabels(display_labels, fontsize=10)
    ax.set_ylim(0, max(max(dm_reads), max(sa_reads)) * 1.2)
    ax.grid(axis="y", linestyle="--", alpha=0.5)
    ax.legend(loc="upper left", framealpha=0.9)

    ax.bar_label(rects1, fmt="%d", padding=3, fontsize=9)
    ax.bar_label(rects2, fmt="%d", padding=3, fontsize=9)

    path3 = os.path.join(OUT_DIR, "memory_reads_comparison.png")
    fig.tight_layout()
    fig.savefig(path3)
    plt.close(fig)
    generated_plots.append(path3)
    print(f"[PLOT] Saved: {path3}")

    return generated_plots


def main():
    print(f"[INFO] Analyzing cache performance results from: {CSV_PATH}")
    records = validate_and_load_csv(CSV_PATH)
    print_summary_table(records)
    plots = generate_plots(records)
    if plots:
        print(f"[SUCCESS] All {len(plots)} comparison plots successfully generated!")
    else:
        print("[INFO] Plots were skipped due to missing matplotlib.")


if __name__ == "__main__":
    main()
